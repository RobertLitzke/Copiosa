package com.copiosa.data.local

import androidx.room.DatabaseView
import androidx.room.Entity
import androidx.room.ForeignKey
import androidx.room.Index
import androidx.room.PrimaryKey
import com.copiosa.domain.model.CardKind
import com.copiosa.domain.model.FlashcardState
import com.copiosa.domain.model.ReviewDirection

/**
 * One thing being learned — a word, a phrase, a sentence, a conjugation — and everything that is
 * true of it whichever way it is asked: both sides of its text, its grammar, its example, its image.
 *
 * This is Anki's split, adopted deliberately. A note is the content; a [CardEntity] is one way of
 * being asked about it, with a schedule of its own. Before it, each direction was a whole row with
 * its own copy of the text, and the two copies drifted — a typo fixed on one side, an example
 * generated twice. Content now has exactly one place to live, so the two directions of a word cannot
 * disagree about what the word is.
 *
 * [term] is always the target-language side and [translation] the native one, so nothing downstream
 * needs to ask which way round a row is stored.
 */
@Entity(tableName = "notes", indices = [Index("targetLanguage"), Index("ankiNoteGuid")])
data class NoteEntity(
    @PrimaryKey(autoGenerate = true) val id: Long = 0,
    val term: String,
    val translation: String,
    val contextSentence: String? = null,
    // Where the word was saved from, at most one of the three: a chat or imported text (the
    // conversation's mode says which), a book, or one generated routine run. All null for a word
    // typed in, seeded, or brought in from Anki. Plain ids, no foreign key: the source going away
    // must not take the word with it.
    val sourceConversationId: Long? = null,
    val sourceBookId: Long? = null,
    val sourceRoutineRunId: Long? = null,
    // LLM-generated enrichment, populated on demand (single "explain" or batched "fill").
    val explanation: String? = null,
    // Short usage/register note kept separate from [translation] so the gloss stays clean (just the
    // 1-3 gloss strings). Split out of a crammed translation on save/import, or typed by the user.
    val usageNote: String? = null,
    val partOfSpeech: String? = null,
    val cefrLevel: String? = null,
    // [cardKind] gates LLM-vocab use + highlighting (only VOCAB/PHRASE). [gender] is M/F/MF/MPL/FPL
    // for display ("el"/"la"), null when not a gendered noun. [country] is a user-set free-text
    // country the word is specific to (e.g. "México"); null when not country-specific. [altForms]
    // holds "; "-joined synonyms/gendered variants (the primary stays in [term]), shown as accepted
    // answers when the term is the answer.
    // [region] is a retired auto-imported dialect slug: no longer read, written, or displayed.
    val cardKind: CardKind = CardKind.VOCAB,
    val gender: String? = null,
    val region: String? = null,
    val country: String? = null,
    val altForms: String? = null,
    // Precomputed surface forms for highlighting: a ";"-joined set of normalized inflections
    // (plurals/conjugations) of [term], so the renderer can light up "gatos" for a saved "gato"
    // without a per-open dictionary lookup. Filled on save/edit and by a background backfill (see
    // FlashcardRepository); null means "not computed yet" (renderer falls back to the headword).
    val inflectedForms: String? = null,
    val targetLanguage: String,
    val nativeLanguage: String,
    val createdAt: Long,
    // User-flagged "marked" (Anki's own term, and in Anki a tag on the note): toggled from review or
    // the editor and used to filter the vocabulary list.
    val marked: Boolean = false,
    // How this note came to exist, when it wasn't the user saving a word: "freq" for the frequency
    // list seeder, "bulk" for the typed-list bulk add, "json" for one a JSON import introduced,
    // "course:<id>" for graduation cards. Null for everything a person saved one at a time or
    // brought in from Anki. Provenance only — it changes no behaviour, and exists so a batch
    // generated by a since-fixed bug can be found and cleaned up without guessing from timestamps.
    // Round-trips through .apkg as an `la:auto` tag.
    val autoSource: String? = null,
    // Anki provenance + passthrough, set on notes imported from a .apkg so a re-export reconstructs
    // the original losslessly and a re-import updates in place. [ankiFieldsJson] keeps every original
    // field ([term]/[translation] are only a display projection of two of them). All null for notes
    // created in Copiosa.
    val ankiNoteGuid: String? = null,
    val ankiNoteTypeId: Long? = null,
    val ankiFieldsJson: String? = null,
    val ankiTags: String? = null,
    val ankiDeckName: String? = null,
    // Media filenames in the app media store.
    val imageFile: String? = null,
    val audioFile: String? = null,
)

/**
 * One direction of a [NoteEntity], and the only thing a review is ever *of*.
 *
 * [direction] is which side is shown first — [ReviewDirection.TARGET_FIRST] (recognise the word) or
 * [ReviewDirection.NATIVE_FIRST] (produce it) — and a note has at most one card of each. The two are
 * scheduled independently because they are different memories: on the deck this was designed
 * against, the produce-it cards had lapsed about twice as often as the recognise-it ones.
 *
 * Ids are the old flashcard row ids, carried over unchanged, which is what kept every `reviews` row
 * attached through the split.
 */
@Entity(
    tableName = "cards",
    foreignKeys = [
        ForeignKey(
            entity = NoteEntity::class,
            parentColumns = ["id"],
            childColumns = ["noteId"],
            onDelete = ForeignKey.CASCADE,
        ),
    ],
    indices = [Index("noteId", "direction", unique = true)],
)
data class CardEntity(
    @PrimaryKey(autoGenerate = true) val id: Long = 0,
    val noteId: Long,
    /** [ReviewDirection.TARGET_FIRST] or [ReviewDirection.NATIVE_FIRST]; never `BOTH`. */
    val direction: ReviewDirection,
    // Spaced-repetition state. [dueAt]/[state]/[lastReviewedAt] plus the FSRS memory state
    // ([stability]/[difficulty]/[fsrsStep]) are what the FSRS engine reads and writes. The SM-2-shaped
    // fields ([intervalDays]/[easeFactor]/[repetitions]/[lapses]) are kept populated so an Anki .apkg
    // export has classic-scheduler columns to fill. stability == null means the card is new to FSRS.
    val dueAt: Long,
    val intervalDays: Double = 0.0,
    val easeFactor: Double = 2.5,
    val repetitions: Int = 0,
    val lapses: Int = 0,
    val lastReviewedAt: Long? = null,
    val state: FlashcardState = FlashcardState.NEW,
    val stability: Double? = null,
    val difficulty: Double? = null,
    val fsrsStep: Int? = null,
    // "Frozen" — this direction is set aside. Per card, as in Anki: a word can be dropped from
    // production practice while still being recognised. Keeps its schedule for when it is unfrozen.
    val suspended: Boolean = false,
    // The Anki template ordinal this card was imported as; with the note's guid it identifies one
    // specific Anki card. Null for a card made in Copiosa.
    val ankiOrd: Int? = null,
)

/**
 * The SQL behind [FlashcardEntity]. Shared with the migration that first creates the view, because
 * Room checks a view's stored definition against this text character for character.
 */
const val FLASHCARDS_VIEW_SQL =
    "SELECT c.id AS id, n.term AS front, n.translation AS back, n.contextSentence AS contextSentence, " +
        "n.sourceConversationId AS sourceConversationId, n.sourceBookId AS sourceBookId, " +
        "n.sourceRoutineRunId AS sourceRoutineRunId, n.explanation AS explanation, " +
        "n.usageNote AS usageNote, n.partOfSpeech AS partOfSpeech, n.cefrLevel AS cefrLevel, " +
        "n.cardKind AS cardKind, n.gender AS gender, n.region AS region, n.country AS country, " +
        "n.altForms AS altForms, n.inflectedForms AS inflectedForms, 1 AS frontIsTarget, " +
        "c.direction AS reviewDirection, n.targetLanguage AS targetLanguage, " +
        "n.nativeLanguage AS nativeLanguage, n.createdAt AS createdAt, c.dueAt AS dueAt, " +
        "c.intervalDays AS intervalDays, c.easeFactor AS easeFactor, c.repetitions AS repetitions, " +
        "c.lapses AS lapses, c.lastReviewedAt AS lastReviewedAt, c.state AS state, " +
        "c.stability AS stability, c.difficulty AS difficulty, c.fsrsStep AS fsrsStep, " +
        "c.suspended AS suspended, n.marked AS marked, n.autoSource AS autoSource, " +
        "n.ankiNoteGuid AS ankiNoteGuid, c.ankiOrd AS ankiOrd, n.ankiNoteTypeId AS ankiNoteTypeId, " +
        "n.ankiFieldsJson AS ankiFieldsJson, n.ankiTags AS ankiTags, n.ankiDeckName AS ankiDeckName, " +
        "n.imageFile AS imageFile, n.audioFile AS audioFile, c.noteId AS noteId " +
        "FROM cards c INNER JOIN notes n ON n.id = c.noteId"

/**
 * A card together with its note's content: the row a review, a session or a list works with.
 *
 * This is a **view**, not a table — `cards` joined to `notes` — so it can be read and never written.
 * It keeps the name and shape the single `flashcards` table had, which is what let the split into
 * notes and cards land without rewriting every query and every consumer at once: the forty-odd
 * `SELECT … FROM flashcards` statements still mean what they meant. Writes go through
 * [FlashcardDao], which sends content to the note and scheduling to the card.
 *
 * Two fields are fixed points now and survive only for the code that still reads them. [front] is
 * always the target-language term and [back] the native one, so [frontIsTarget] is always true when
 * read from the database — it is false only on a row [com.copiosa.data.anki.AnkiImporter] has just
 * built from a reverse template, on its way to being stored the right way round. And
 * [reviewDirection] is the card's own direction, never `BOTH`, except on a row describing a card
 * still to be created, where `BOTH` asks for one card each way.
 */
@DatabaseView(viewName = "flashcards", value = FLASHCARDS_VIEW_SQL)
data class FlashcardEntity(
    /** The **card's** id. */
    val id: Long = 0,
    val front: String,
    val back: String,
    val contextSentence: String? = null,
    val sourceConversationId: Long? = null,
    val sourceBookId: Long? = null,
    val sourceRoutineRunId: Long? = null,
    val explanation: String? = null,
    val usageNote: String? = null,
    val partOfSpeech: String? = null,
    val cefrLevel: String? = null,
    val cardKind: CardKind = CardKind.VOCAB,
    val gender: String? = null,
    val region: String? = null,
    val country: String? = null,
    val altForms: String? = null,
    val inflectedForms: String? = null,
    val frontIsTarget: Boolean = true,
    val reviewDirection: ReviewDirection = ReviewDirection.TARGET_FIRST,
    val targetLanguage: String,
    val nativeLanguage: String,
    val createdAt: Long,
    val dueAt: Long,
    val intervalDays: Double = 0.0,
    val easeFactor: Double = 2.5,
    val repetitions: Int = 0,
    val lapses: Int = 0,
    val lastReviewedAt: Long? = null,
    val state: FlashcardState = FlashcardState.NEW,
    val stability: Double? = null,
    val difficulty: Double? = null,
    val fsrsStep: Int? = null,
    val suspended: Boolean = false,
    val marked: Boolean = false,
    val autoSource: String? = null,
    val ankiNoteGuid: String? = null,
    val ankiOrd: Int? = null,
    val ankiNoteTypeId: Long? = null,
    val ankiFieldsJson: String? = null,
    val ankiTags: String? = null,
    val ankiDeckName: String? = null,
    val imageFile: String? = null,
    val audioFile: String? = null,
    /** The note this card belongs to; 0 on a row not yet stored. Cards sharing it are siblings. */
    val noteId: Long = 0,
)

/**
 * What this row's siblings share: its note. A row not yet stored has no note id, and is a note of
 * its own — which is also what keeps rows built in a test from all reading as one word.
 */
val FlashcardEntity.noteKey: Long get() = if (noteId != 0L) noteId else -id

/** The direction a stored card has for this row: `BOTH` and target-first both begin with the term. */
val FlashcardEntity.cardDirection: ReviewDirection
    get() = if (reviewDirection == ReviewDirection.NATIVE_FIRST) ReviewDirection.NATIVE_FIRST else ReviewDirection.TARGET_FIRST

/** This row's content as the note that holds it, the right way round whichever way the row faces. */
fun FlashcardEntity.toNote(id: Long = noteId): NoteEntity = NoteEntity(
    id = id,
    term = if (frontIsTarget) front else back,
    translation = if (frontIsTarget) back else front,
    contextSentence = contextSentence,
    sourceConversationId = sourceConversationId,
    sourceBookId = sourceBookId,
    sourceRoutineRunId = sourceRoutineRunId,
    explanation = explanation,
    usageNote = usageNote,
    partOfSpeech = partOfSpeech,
    cefrLevel = cefrLevel,
    cardKind = cardKind,
    gender = gender,
    region = region,
    country = country,
    altForms = altForms,
    inflectedForms = inflectedForms,
    targetLanguage = targetLanguage,
    nativeLanguage = nativeLanguage,
    createdAt = createdAt,
    marked = marked,
    autoSource = autoSource,
    ankiNoteGuid = ankiNoteGuid,
    ankiNoteTypeId = ankiNoteTypeId,
    ankiFieldsJson = ankiFieldsJson,
    ankiTags = ankiTags,
    ankiDeckName = ankiDeckName,
    imageFile = imageFile,
    audioFile = audioFile,
)

/** This row's schedule as the card that holds it. */
fun FlashcardEntity.toCard(
    noteId: Long = this.noteId,
    direction: ReviewDirection = cardDirection,
    id: Long = this.id,
): CardEntity = CardEntity(
    id = id,
    noteId = noteId,
    direction = direction,
    dueAt = dueAt,
    intervalDays = intervalDays,
    easeFactor = easeFactor,
    repetitions = repetitions,
    lapses = lapses,
    lastReviewedAt = lastReviewedAt,
    state = state,
    stability = stability,
    difficulty = difficulty,
    fsrsStep = fsrsStep,
    suspended = suspended,
    ankiOrd = ankiOrd,
)
