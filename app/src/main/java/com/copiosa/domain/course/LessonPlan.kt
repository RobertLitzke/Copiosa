package com.copiosa.domain.course

import com.copiosa.domain.routine.ClozeItem
import com.copiosa.domain.routine.ConjugationDrillItem
import com.copiosa.domain.routine.PiItem
import kotlinx.serialization.SerialName
import kotlinx.serialization.Serializable

/**
 * A materialized course session, ready for the player: the authored skeleton resolved into concrete
 * segments, with drill items selected and any LLM slots filled (or dropped). Serialized into
 * `course_sessions.planJson` by [LessonPlanCodec] so a session survives process death;
 * `currentIndex` on the row is the resume point, mirroring `routine_runs`.
 *
 * Like the routine plan, only *coordinates* are stored for anything the engine can re-derive —
 * drill items, table references — so a saved plan stays small and can never carry a stale form.
 */
@Serializable
data class LessonPlan(
    val courseId: String,
    /** Null for a checkup, which spans the whole course rather than one lesson. */
    val lessonId: String? = null,
    val targetLanguage: String,
    val sessionKind: SessionKind,
    val segments: List<LessonSegment>,
)

/** What kind of sitting this is. Names are persisted in `course_sessions.kind` — frozen. */
@Serializable
enum class SessionKind {
    LESSON,
    CHECKUP,
    MICRO_LESSON,
    ;

    companion object {
        fun fromName(name: String?): SessionKind? = entries.firstOrNull { it.name == name }
    }
}

/**
 * One step of a session. Closed hierarchy discriminated by `"kind"`; `@SerialName`s are **frozen**.
 * Unlike `ActivityContent`, an unknown kind in a stored plan is *dropped by the codec*, not fatal —
 * so retiring a segment kind needs no `@Deprecated` stub, old sessions just get shorter.
 */
@Serializable
sealed interface LessonSegment

/** A teaching beat: prose, live tables, worked examples. */
@Serializable
@SerialName("didactic")
data class DidacticSegment(
    val title: String? = null,
    val blocks: List<LessonBlock>,
) : LessonSegment

/**
 * A conjugation-drill beat. [items] reuses the routine plan's coordinate encoding
 * ([ConjugationDrillItem], via `DrillItemCodec`), so forms and colour segments are re-derived at
 * render time. [warmUp] marks the retrieval opener drawn from *earlier* lessons, so the player can
 * frame it ("from last time") and the results feed pacing, not this lesson's accuracy.
 */
@Serializable
@SerialName("conj_drill")
data class ConjDrillSegment(
    val items: List<ConjugationDrillItem>,
    val language: String,
    val warmUp: Boolean = false,
) : LessonSegment

/**
 * A cloze beat — generated by the LLM, or materialized from a lesson's authored bank. Answers bucket
 * to [category] when set (a contrast-category slug). [warmUp] marks the retrieval opener drawn from
 * *earlier* lessons, exactly as it does on [ConjDrillSegment]: a non-morphological course has no
 * conjugation cards to open on, so its warm-up is a handful of items the earlier lessons taught.
 */
@Serializable
@SerialName("cloze")
data class ClozeSegment(
    val items: List<ClozeItem>,
    val category: String? = null,
    val warmUp: Boolean = false,
) : LessonSegment

/** An LLM-generated referential-PI beat: the verb form alone reveals who/when. */
@Serializable
@SerialName("pi")
data class PiSegment(
    val items: List<PiItem>,
    val category: String? = null,
) : LessonSegment

/** The closing screen. [feedback] is the optional LLM error diagnosis, filled in after play. */
@Serializable
@SerialName("wrap_up")
data class WrapUpSegment(
    val summary: String? = null,
    val feedback: String? = null,
) : LessonSegment

/** One block inside a [DidacticSegment] — the serialized twin of [DidacticBlock]. */
@Serializable
sealed interface LessonBlock

@Serializable
@SerialName("prose")
data class ProseBlock(val text: String) : LessonBlock

/** A live table reference: tense and person *slugs*, resolved against the spec at render time. */
@Serializable
@SerialName("table")
data class TableBlock(
    val tense: String,
    val verbs: List<String>,
    val persons: List<String>? = null,
) : LessonBlock

@Serializable
@SerialName("examples")
data class ExamplesBlock(val items: List<ExampleItem>) : LessonBlock

/** A worked example: [cell] is a cell slug ("pret.1s") or null for whole-sentence contrasts. */
@Serializable
data class ExampleItem(
    val infinitive: String,
    val cell: String? = null,
    val sentence: String,
    val gloss: String,
    val note: String? = null,
)
